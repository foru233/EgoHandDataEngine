# 数据源统一生命周期：open→start→read→stop→close；元数据/标定必须独立可查询。

from abc import ABC, abstractmethod

# 真实 SDK、录制和合成源都遵守此接口；read 返回的图像所有权/时间依据由实现明确。
class StereoDataSource(ABC):
    @abstractmethod
    def open(self): ...
    @abstractmethod
    def start(self): ...
    @abstractmethod
    def read(self): ...
    @abstractmethod
    def stop(self): ...
    @abstractmethod
    def close(self): ...
    @abstractmethod
    def get_metadata(self): ...
    @abstractmethod
    def get_calibration(self): ...
